package com.caixa.eodguardian.patch;

public enum PatchStatus {
    RECOMMENDED,        // generated by the Data Patch Recommendation Agent, not yet owned by a human
    PENDING_APPROVAL,   // submitted by a maker
    APPROVED,           // authorised by a checker (different user)
    REJECTED,
    EXECUTED,           // applied by an operator (different from maker and checker)
    EXECUTION_FAILED,   // pre/post validation or precondition failed - nothing left applied
    ROLLED_BACK,
    SUPERSEDED
}
